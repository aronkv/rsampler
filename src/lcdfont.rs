//! The LCD's dot-matrix font, drawn dot by dot so every character stays sharp, accents included.
//!
//! The glyphs are the public-domain X11 "fixed" 6x10 font (ASCII, Latin-1, Latin Extended-A and
//! some punctuation), with square stops in place of its diamond ones, in a 6x14 cell: two rows
//! above it so capitals get their accents in rows of their own instead of squeezed onto the
//! letter, and two below. Rows top down; in each row bit 5 is the leftmost dot.

use eframe::egui::{Align2, Color32, FontId, Mesh, Painter, Pos2, Rect, Shape, pos2, vec2};

const COLS: usize = 6;
const ROWS: usize = 14;

/// Width of `text` with dots `dot` points apart.
pub fn width(text: &str, dot: f32) -> f32 {
    text.chars().count() as f32 * COLS as f32 * dot
}

/// Draws `text` placed by `align` at `pos`, dots `dot` points apart. Each dot is snapped to whole
/// screen pixels, so all copies of a character look the same; below a pixel per dot no dot font
/// is readable, and the text is drawn in the smooth monospace font of the same size instead.
pub fn paint(painter: &Painter, pos: Pos2, align: Align2, text: &str, dot: f32, color: Color32) {
    let ppp = painter.pixels_per_point();
    if dot * ppp < 1.0 {
        painter.text(pos, align, text, FontId::monospace(dot * 10.0), color);
        return;
    }
    // Aligned on the 13 rows a highlighted field covers, whose middle is that of the capitals.
    let top_left = align.anchor_size(pos, vec2(width(text, dot), (ROWS - 1) as f32 * dot)).min;
    let snap = |v: f32| (v * ppp).round() / ppp;
    let edge = |i: usize| snap(i as f32 * dot);
    let y = snap(top_left.y);
    let mut mesh = Mesh::default();
    for (n, c) in text.chars().enumerate() {
        let x = snap(top_left.x + (n * COLS) as f32 * dot);
        for (r, &bits) in glyph(c).iter().enumerate() {
            let mut col = 0;
            while col < COLS {
                if bits >> (COLS - 1 - col) & 1 == 0 {
                    col += 1;
                    continue;
                }
                // A run of dots in a row is one rectangle.
                let start = col;
                while col < COLS && bits >> (COLS - 1 - col) & 1 == 1 {
                    col += 1;
                }
                let rect = Rect::from_min_max(pos2(x + edge(start), y + edge(r)), pos2(x + edge(col), y + edge(r + 1)));
                mesh.add_colored_rect(rect, color);
            }
        }
    }
    painter.add(Shape::mesh(mesh));
}

/// The dots of `c`; characters the font lacks show as `?`, as on a real LCD.
fn glyph(c: char) -> &'static [u8; ROWS] {
    GLYPHS.binary_search_by_key(&c, |g| g.0).map_or_else(|_| glyph('?'), |i| &GLYPHS[i].1)
}

