mod tests {
    use super::*;

    #[test]
    fn glyphs_are_sorted_and_capital_accents_sit_above_the_letter() {
        assert!(GLYPHS.windows(2).all(|w| w[0].0 < w[1].0));
        // The capital fills rows 3-9 like the plain letter, with the accent above a blank row.
        let (a, accented) = (glyph('O'), glyph('Ő'));
        assert_eq!(a[3..], accented[3..]);
        assert_eq!(accented[2], 0);
        assert!(accented[..2].iter().all(|&r| r != 0));
        assert_eq!(glyph('\u{1F600}'), glyph('?'));
    }
}
